def test_employment_availability_history_and_explanation_are_distinct() -> None:
    questions = (
        "Есть ли у тебя возможность официального оформления?",
        "Оформлены ли вы по ТК РФ в указанных в резюме компаниях?",
        "Оформлены ли вы по ТК РФ в указанных в резюме компаниях? "
        "(если нет, то распишите, в каких компаниях и как оформлены)",
    )
    keys = {reusable_question_key(question) for question in questions}
    assert None not in keys
    assert len(keys) == 3


