def test_matching_numbers_from_different_facts_do_not_combine_into_evidence() -> None:
    sources = ("Обработал 100 заявок", "Увеличил выручку на 20 процентов")
    assert unsupported_numeric_claim("Увеличил выручку на 100 процентов", sources)


def test_technology_version_is_not_a_personal_quantity() -> None:
    assert unsupported_numeric_claim("Работал с Python 3.12", ("Python 3.12",)) is None
    assert unsupported_numeric_claim("Работал с Python 12 лет", ("Python 3.12",)) is not None


def test_no_numbers_do_not_need_quantitative_evidence() -> None:
    assert unsupported_numeric_claim("Разрабатывал серверные приложения", ()) is None


def test_project_from_previous_sentence_is_preserved() -> None:
    source = "Разрабатывал проект Alpha. Обработал 100 заявок. Проект Beta. Обработал 20 заявок."
    assert unsupported_numeric_claim("Проект Beta. Обработал 100 заявок", (source,))
    assert unsupported_numeric_claim("Проект Alpha. Обработал 100 заявок", (source,)) is None


def test_unrecognized_metric_requires_exact_source() -> None:
    assert unsupported_numeric_claim("Настроил 7 контуров", ("Настроил 7 контуров",)) is None
    assert unsupported_numeric_claim("Построил 7 предприятий", ("Настроил 7 контуров",))
